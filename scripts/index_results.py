"""Index local result folders without modifying experiments or inferring success."""

import argparse
from collections import defaultdict
from datetime import datetime, timezone
import json
import os
from pathlib import Path
from urllib.parse import quote


def footprint(path):
    if path.is_symlink():
        return 0, 0
    if path.is_file():
        return path.stat().st_size, 1
    size = count = 0
    for directory, _, files in os.walk(path, followlinks=False):
        for name in files:
            item = Path(directory) / name
            if not item.is_symlink():
                size += item.stat().st_size
                count += 1
    return size, count


def category(path):
    name = path.name
    if path.is_symlink():
        return 'Compatibility links'
    if name == 'exports':
        return 'Downloadable exports'
    if name == 'archive':
        return 'Archived drafts'
    if name.startswith('scaling-') and 'gallery' not in name:
        return 'Planning campaigns'
    if name.startswith(('plans-', 'architecture-', 'scaling-gallery')):
        return 'Visualizations'
    if name.startswith('px4-'):
        return 'PX4/Gazebo runs'
    if name in ('trajectory2d', 'trajectory3d'):
        return 'Trajectory runs'
    if name == 'benchmarks':
        return 'Historical benchmarks'
    if 'smoke' in name:
        return 'GUI checks'
    if name.endswith('.csv'):
        return 'Telemetry'
    return 'Diagnostics and development'


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--results', type=Path, default=Path('results'))
    args = parser.parse_args(argv)
    root = args.results
    if not root.is_dir():
        parser.error('results directory does not exist')
    rows = []
    for path in sorted(root.iterdir()):
        if path.name in ('README.md', 'inventory.json', 'cleanup-20261028.json'):
            continue
        size, count = footprint(path)
        rows.append({'path': path.name, 'category': category(path), 'bytes': size, 'files': count,
                     'kind': 'symlink' if path.is_symlink() else 'directory' if path.is_dir() else 'file',
                     'link_target': os.readlink(path) if path.is_symlink() else None})
    document = {'generated_utc': datetime.now(timezone.utc).isoformat(),
        'scope': 'filesystem inventory only; no experiment acceptance or independent revalidation',
        'size_scope': 'logical regular-file bytes; symlinks excluded; no directory overhead',
        'total_bytes': sum(r['bytes'] for r in rows), 'entries': rows}
    (root / 'inventory.json').write_text(json.dumps(document, indent=2)+'\n')
    lines = ['# Local result index', '',
        'Generated by `scripts/index_results.py`. This directory is ignored by Git. '
        'Original plans, failed experiments, source fingerprints and logs are retained.', '',
        'Sizes are logical regular-file sizes, not allocated disk blocks. Compatibility links are not counted twice. '
        'This index does not infer success or independently validate trajectories.', '', '## Current deliverables', '']
    highlights = [('Scaling campaign report', 'scaling-campaign-20261028/analysis/report.pdf'),
        ('Scaling campaign findings', 'scaling-campaign-20261028/analysis/findings.md'),
        ('All 418 planning measurements', 'scaling-campaign-20261028/analysis/missions.csv'),
        ('46 five-aircraft scenes and plans', 'plans-46-5drones-20261028/index.html'),
        ('46-page plan gallery', 'plans-46-5drones-20261028/plans.pdf'),
        ('Architecture diagram', 'architecture-diagram/architecture.pdf'),
        ('Complete campaign download', 'exports/trajectory-campaign-20261028.zip')]
    for label, relative in highlights:
        if (root / relative).is_file():
            lines.append(f'- [{label}]({quote(relative)})')
    groups = defaultdict(list)
    for row in rows:
        groups[row['category']].append(row)
    for group, entries in groups.items():
        lines += ['', '## '+group, '', '| Location | Size (MiB) | Files |', '|---|---:|---:|']
        for row in entries:
            suffix = f" → `{row['link_target']}`" if row['link_target'] else ''
            lines.append(f"| [{row['path']}]({quote(row['path'])}){suffix} | {row['bytes']/1024**2:.2f} | {row['files']} |")
    lines += ['', '## Preservation rules', '',
        '- Historical trajectory/PX4 run folders keep their original locations and contents.',
        '- Campaign manifests, source snapshots and original ZIP contents are not rewritten.',
        '- Published archive paths remain usable through relative compatibility symlinks.',
        '- `archive/visualization-drafts/` contains the superseded gallery, not new experiment results.',
        '- Regenerable Python/pytest caches are outside the retained experiment evidence.',
        '- Keep `.venv` and editable-install metadata under `src/*.egg-info`; they belong to the working environment.', '']
    (root / 'README.md').write_text('\n'.join(lines))
    print(f'Indexed {len(rows)} entries, {document["total_bytes"]/1024**3:.2f} GiB of regular files: {root / "README.md"}')


if __name__ == '__main__':
    main()
